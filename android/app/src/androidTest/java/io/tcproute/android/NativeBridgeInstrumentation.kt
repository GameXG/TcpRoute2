package io.tcproute.android

import android.app.Activity
import android.app.Instrumentation
import android.os.Bundle
import java.io.File
import java.util.Base64

class NativeBridgeInstrumentation : Instrumentation() {
    override fun onCreate(arguments: Bundle?) {
        super.onCreate(arguments)
        start()
    }

    override fun onStart() {
        val results = Bundle()
        try {
            val probe = Tun2ProxyBridge.probe()
            check(probe == 1) { "Unexpected native bridge probe result: $probe" }
            results.putString("native_bridge", "loaded")

            check("socks4" !in CREATABLE_PROXY_SCHEMES && "socks4a" !in CREATABLE_PROXY_SCHEMES) {
                "Removed SOCKS4 types are still offered for new upstreams"
            }
            val dialRaw = "addr=\"127.0.0.1:7070\"\n[[UpStreams]]\nName=\"front\"\nProxyUrl=\"socks5://127.0.0.1:1080\"\nDialProxyFor=\"target\"\n[[UpStreams]]\nName=\"target\"\nProxyUrl=\"https://127.0.0.1:8443\"\n"
            val dialDraft = TcpRouteConfigStore.parseEditableConfig(dialRaw)
            check(dialDraft.upstreams.first { it.name == "front" }.dialProxyFor == "target" &&
                TcpRouteConfigStore.renderEditableConfig(dialDraft).contains("DialProxyFor=\"target\"")) { "Android codec dropped DialProxyFor" }
            val removedDraft = TcpRouteConfigStore.parseEditableConfig(dialRaw.replace("DialProxyFor=\"target\"", "DialProxyFor=\"target\"\nRemove=true"))
            check(removedDraft.upstreams.first { it.name == "front" }.remove &&
                TcpRouteConfigStore.renderEditableConfig(removedDraft).contains("Remove=true")) { "Android codec dropped Remove" }
            val clashNodes = SubscriptionStore.parse("proxies:\n  - name: clash\n    type: http\n    server: example.com\n    port: 8080\n")
            check(clashNodes.single().proxyUrl == "http://example.com:8080") { "Android Clash subscription extraction failed" }
            val surgeNodes = SubscriptionStore.parse("[Proxy]\nSurge = socks5, example.com, 1080\n")
            check(surgeNodes.single().proxyUrl == "socks5://example.com:1080") { "Android Surge subscription extraction failed" }

            val longVmessJson = """{"v":"2","ps":"long-validation-link","add":"example.com","port":"443","id":"11111111-1111-1111-1111-111111111111","aid":"0","net":"ws","type":"none","host":"example.com","path":"/a/long/websocket/path","tls":"tls","sni":"example.com","alpn":"h2,http/1.1","fp":"chrome"}"""
            val longVmess = "vmess://" + Base64.getUrlEncoder().withoutPadding()
                .encodeToString(longVmessJson.toByteArray(Charsets.UTF_8))
            check(TcpRouteConfigStore.proxyUrlError(longVmess) == null) {
                "A valid long VMess JSON URL was rejected"
            }
            check(TcpRouteConfigStore.proxyUrlError("vmess://not base64") == "Proxy URL is empty or contains whitespace.")
            check(TcpRouteConfigStore.proxyUrlError("vmess://not-base64!") == "VMess URL payload is not valid Base64.")
            val incompleteVmess = "vmess://" + Base64.getEncoder().encodeToString("{\"add\":\"example.com\"}".toByteArray())
            check(TcpRouteConfigStore.proxyUrlError(incompleteVmess) == "VMess JSON payload is incomplete.")
            results.putString("vmess_validation", "long links accepted and detailed failures classified")

            val geosite = EditableDomainList(
                path = "geosite.dat",
                sourceType = SOURCE_GEOSITE,
                type = "gfw,google,bing"
            )
            val dnsRaw = "addr=\"127.0.0.1:7070\"\n[[Dns]] # primary\nType=\"doh\"\nURL=\"https://dns.example/dns-query\"\nPriority=10\nTimeout=\"3s\"\n[[Dns]]\nType=\"system\"\nPriority=20\n"
            val dnsDraft = TcpRouteConfigStore.parseEditableConfig(dnsRaw)
            check(dnsDraft.dnsToml.contains("Priority=20") && TcpRouteConfigStore.renderEditableConfig(dnsDraft).contains(dnsDraft.dnsToml)) {
                "Quick save dropped DNS configuration"
            }
            val config = EditableTcpRouteConfig(
                upstreams = listOf(EditableUpstream.direct().copy(whitelist = listOf(geosite)))
            )
            val rendered = TcpRouteConfigStore.renderEditableConfig(config)
            check(rendered.startsWith("addr=\"")) { "Generated config contains an unnecessary client comment" }
            check(
                TcpRouteConfigStore.stripLegacyGeneratedComment(
                    "# TcpRoute config generated by TcpRoute Android\n$rendered"
                ) == rendered
            ) { "Legacy Android generated comment was not hidden" }
            check("Type=\"geosite\"" in rendered) { "Geosite Type was not serialized" }
            check("Path=\"geosite:gfw,geosite:google,geosite:bing\"" in rendered) { "Geosite selectors were not serialized" }
            val parsed = TcpRouteConfigStore.parseEditableConfig(rendered).upstreams.single().whitelist.single()
            check(parsed.type == "gfw,google,bing" && parsed.path == "geosite.dat" && parsed.sourceType == SOURCE_GEOSITE) {
                "Geosite Type and Path did not round-trip"
            }
            val migratedTypeOnly = TcpRouteConfigStore.parseEditableConfig(
                rendered.replace("Type=\"geosite\"\nPath=\"geosite:gfw,geosite:google,geosite:bing\"", "Type=\"geosite:gfw,google,bing\"")
            ).upstreams.single().whitelist.single()
            check(migratedTypeOnly.type == "gfw,google,bing" && migratedTypeOnly.path == "geosite.dat") {
                "Type-only Geosite preview config was not migrated"
            }
            val migratedPathOnly = TcpRouteConfigStore.parseEditableConfig(
                rendered.replace("Type=\"geosite\"\nPath=\"geosite:gfw,geosite:google,geosite:bing\"", "Path=\"geosite:gfw\"")
            ).upstreams.single().whitelist.single()
            check(migratedPathOnly.type == "gfw" && migratedPathOnly.path == "geosite.dat") {
                "Path-only Geosite preview config was not migrated"
            }
            val remoteGeosite = EditableTcpRouteConfig(
                upstreams = listOf(
                    EditableUpstream.direct().copy(
                        whitelist = listOf(
                            geosite.copy(
                                path = "https://example.com/geosite.dat",
                                updateInterval = "6h"
                            )
                        )
                    )
                )
            )
            val renderedRemoteGeosite = TcpRouteConfigStore.renderEditableConfig(remoteGeosite)
            check("Path=\"https://example.com/geosite.dat\"" in renderedRemoteGeosite) {
                "Remote Geosite Path was not serialized"
            }
            check("UpdateInterval=\"6h\"" in renderedRemoteGeosite) {
                "Remote Geosite update interval was not serialized"
            }
            val parsedRemoteGeosite = TcpRouteConfigStore.parseEditableConfig(renderedRemoteGeosite)
                .upstreams.single().whitelist.single()
            check(parsedRemoteGeosite.sourceType == SOURCE_GEOSITE && parsedRemoteGeosite.updateInterval == "6h") {
                "Remote Geosite config did not round-trip"
            }
            results.putString("geosite_config", "compact multi-list rules plus local/remote Path supported")

            val geoip = EditableDomainList(
                path = "geoip.dat",
                sourceType = SOURCE_GEOIP,
                type = "cn,private"
            )
            val geoipConfig = EditableTcpRouteConfig(
                upstreams = listOf(EditableUpstream.direct().copy(blacklist = listOf(geoip)))
            )
            val renderedGeoIP = TcpRouteConfigStore.renderEditableConfig(geoipConfig)
            check("Type=\"geoip\"" in renderedGeoIP && "Path=\"geoip:cn,geoip:private\"" in renderedGeoIP) {
                "GeoIP selector and built-in data path were not serialized"
            }
            val parsedGeoIP = TcpRouteConfigStore.parseEditableConfig(renderedGeoIP)
                .upstreams.single().blacklist.single()
            check(parsedGeoIP.sourceType == SOURCE_GEOIP && parsedGeoIP.type == "cn,private") {
                "GeoIP config did not round-trip"
            }
            val migratedGeoIP = TcpRouteConfigStore.parseEditableConfig(
                renderedGeoIP.replace("Path=\"geoip.dat\"\n", "")
            ).upstreams.single().blacklist.single()
            check(migratedGeoIP.path == "geoip.dat" && migratedGeoIP.sourceType == SOURCE_GEOIP) {
                "Type-only GeoIP config did not restore the built-in data path"
            }
            results.putString("geoip_config", "compact country selectors and built-in data supported")

            val nativeConfig = File(targetContext.cacheDir, "geoip-native-smoke.toml")
            val nativeLog = File(targetContext.cacheDir, "geoip-native-smoke.log")
            var nativeProcess: Process? = null
            try {
                TcpRouteBinaryInstaller.installGeoData(targetContext)
                val geoIPPath = File(targetContext.filesDir, "geoip.dat").absolutePath
                    .replace("\\", "\\\\")
                    .replace("\"", "\\\"")
                nativeConfig.writeText(
                    """
                    addr="127.0.0.1:0"
                    [[UpStreams]]
                    Name="direct"
                    ProxyUrl="direct://0.0.0.0:0000"
                    DnsResolve=true
                    [[UpStreams.Whitelist]]
                    Type="geoip:cn,private"
                    Path="$geoIPPath"
                    """.trimIndent()
                )
                nativeProcess = ProcessBuilder(
                    TcpRouteBinaryInstaller.install(targetContext).absolutePath,
                    "-config",
                    nativeConfig.absolutePath
                )
                    .redirectErrorStream(true)
                    .redirectOutput(nativeLog)
                    .start()
                Thread.sleep(750)
                check(nativeProcess.isAlive) {
                    "Embedded core rejected GeoIP config: ${nativeLog.readText()}"
                }
                results.putString("geoip_native", "embedded ARM64 core accepts geoip:cn,private")
            } finally {
                nativeProcess?.destroy()
                nativeProcess?.waitFor(1, java.util.concurrent.TimeUnit.SECONDS)
                if (nativeProcess?.isAlive == true) nativeProcess.destroyForcibly()
                nativeConfig.delete()
                nativeLog.delete()
            }

            val fileRules = EditableTcpRouteConfig(
                upstreams = listOf(
                    EditableUpstream.direct().copy(
                        whitelist = listOf(
                            EditableDomainList(
                                path = "rules/local.txt",
                                sourceType = SOURCE_LOCAL,
                                type = "suffix"
                            ),
                            EditableDomainList(
                                path = "https://example.com/remote.txt",
                                sourceType = SOURCE_REMOTE,
                                type = "base",
                                updateInterval = "6h"
                            )
                        )
                    )
                )
            )
            val renderedFiles = TcpRouteConfigStore.renderEditableConfig(fileRules)
            check("Path=\"rules/local.txt\"" in renderedFiles) { "Local rule Path was not serialized" }
            check("Path=\"https://example.com/remote.txt\"" in renderedFiles) { "Remote rule Path was not serialized" }
            val parsedFiles = TcpRouteConfigStore.parseEditableConfig(renderedFiles).upstreams.single().whitelist
            check(parsedFiles.map { it.path } == listOf("rules/local.txt", "https://example.com/remote.txt")) {
                "File rule Path did not round-trip"
            }
            results.putString("file_rule_config", "Path preserved for local and remote rules")

            val hostMatchTypes = listOf("base", "suffix", "pan", "regex")
            val hostConfig = EditableTcpRouteConfig(
                hosts = hostMatchTypes.mapIndexed { index, type ->
                    EditableHostSource(
                        path = "hosts/$type.txt",
                        sourceType = SOURCE_LOCAL,
                        type = type,
                        credit = index
                    )
                },
                upstreams = listOf(EditableUpstream.direct())
            )
            val renderedHosts = TcpRouteConfigStore.renderEditableConfig(hostConfig)
            hostMatchTypes.forEach { type ->
                check("Type=\"$type\"" in renderedHosts) { "Host match type $type was not serialized" }
            }
            val parsedHostTypes = TcpRouteConfigStore.parseEditableConfig(renderedHosts).hosts.map { it.type }
            check(parsedHostTypes == hostMatchTypes) { "Host match types did not round-trip: $parsedHostTypes" }
            results.putString("host_match_types", "localized UI selections restore base/suffix/pan/regex")

            val logProbe = File(targetContext.cacheDir, "request-log-reader-test.log")
            try {
                logProbe.writeText("first\nsecond\nthird\n")
                val logSnapshot = TcpRouteLogReader.read(logProbe, maxBytes = 10)
                check(logSnapshot.truncated && logSnapshot.content == "third") {
                    "Request log tail did not discard a partial first line"
                }
                results.putString("request_log_reader", "bounded tail preserves complete recent lines")
            } finally {
                logProbe.delete()
            }

            val logSourceDirectory = File(targetContext.cacheDir, "request-log-source-test").apply { mkdirs() }
            val vpnLog = File(logSourceDirectory, TcpRouteVpnService.LOG_FILE_NAME)
            val socksLog = File(logSourceDirectory, TcpRouteService.LOG_FILE_NAME)
            try {
                vpnLog.writeText("vpn")
                socksLog.writeText("socks")
                check(TcpRouteLogFiles.select(logSourceDirectory, vpnActive = true, socksActive = false) == vpnLog)
                check(TcpRouteLogFiles.select(logSourceDirectory, vpnActive = false, socksActive = true) == socksLog)
                vpnLog.setLastModified(socksLog.lastModified() + 1_000L)
                check(TcpRouteLogFiles.select(logSourceDirectory, vpnActive = false, socksActive = false) == vpnLog)
                TcpRouteLogFiles.clear(vpnLog)
                check(vpnLog.isFile && vpnLog.length() == 0L) { "Clearing must truncate the active log in place" }
                results.putString("request_log_source", "selection and in-place clearing verified")
            } finally {
                vpnLog.delete()
                socksLog.delete()
                logSourceDirectory.delete()
            }
            finish(Activity.RESULT_OK, results)
        } catch (error: Throwable) {
            results.putString("native_bridge_error", error.stackTraceToString())
            finish(Activity.RESULT_CANCELED, results)
        }
    }
}
